function buildReviews(seed: number, rating: number): Review[] {
  return Array.from({ length: 4 }, (_, i) => {
    const t = reviewTitles[(seed + i) % reviewTitles.length];
    const stars = Math.max(3, Math.min(5, Math.round(rating - (i === 3 ? 1 : 0))));
    const day = ((seed * 7 + i * 5) % 27) + 1;
    return {
      id: `r${seed}-${i}`,
      author: reviewers[(seed + i * 3) % reviewers.length],
      rating: stars,
      date: `2026-${String(10 - (i % 3)).padStart(2, "0")}-${String(day).padStart(2, "0")}`,
      title: t[0],
      body: t[1],
      verified: i !== 2,
    };
  });
}

